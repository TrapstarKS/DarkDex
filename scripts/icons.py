"""Builds src/Core/IconAtlas.luau from the icons of an installed Roblox Studio.

The client only ships the legacy ClassImages.PNG strip, which lacks most modern classes.
This packs Studio's current 16x16 dark class icons into one PNG grid, plus the 32x32
icons of the main menu tools, both embedded as base64.

    python3 scripts/icons.py [path to Studio's content folder]
"""

import base64
import io
import pathlib
import sys

from PIL import Image

CONTENT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/Applications/RobloxStudio.app/Contents/Resources/content")
TEXTURES = CONTENT / "studio_svg_textures"
CLASS_ICONS = TEXTURES / "Shared/InsertableObjects/Dark/Standard"
OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "src/Core/IconAtlas.luau"
CLASS_SIZE = 16
CLASS_COLUMNS = 32
MENU_SIZE = 32


def load(path: str, size: int, crop: bool = False) -> Image.Image:
    image = Image.open(TEXTURES / path).convert("RGBA")
    if crop:
        image = image.crop(image.getbbox())
    return image.resize((size, size), Image.LANCZOS)


def with_cursor(path: str) -> Image.Image:
    icon = Image.new("RGBA", (MENU_SIZE, MENU_SIZE))
    icon.alpha_composite(load(path, 28), (0, 0))
    icon.alpha_composite(load("Shared/Ribbon/Dark/Medium/RibbonSelect@3x.png", 18, True), (14, 14))
    return icon


def centered(path: str, size: int) -> Image.Image:
    icon = Image.new("RGBA", (MENU_SIZE, MENU_SIZE))
    offset = (MENU_SIZE - size) // 2
    icon.alpha_composite(load(path, size, True), (offset, offset))
    return icon


def encode(image: Image.Image) -> str:
    png = io.BytesIO()
    image.save(png, "PNG", optimize=True)
    return base64.b64encode(png.getvalue()).decode()


def names_list(names: list[str]) -> str:
    return ", ".join(f'"{name}"' for name in names)


class_names = sorted(path.stem for path in CLASS_ICONS.glob("*.png") if "@" not in path.stem)
rows = -(-len(class_names) // CLASS_COLUMNS)
class_atlas = Image.new("RGBA", (CLASS_COLUMNS * CLASS_SIZE, rows * CLASS_SIZE))
for index, name in enumerate(class_names):
    icon = Image.open(CLASS_ICONS / f"{name}.png").convert("RGBA").resize((CLASS_SIZE, CLASS_SIZE))
    class_atlas.paste(icon, ((index % CLASS_COLUMNS) * CLASS_SIZE, (index // CLASS_COLUMNS) * CLASS_SIZE))

menu_icons = {
    "Click_Part": with_cursor("Shared/Ribbon/Dark/Medium/RibbonPart@3x.png"),
    "Click_Gui": with_cursor("Shared/Ribbon/Dark/Medium/RibbonGUI@3x.png"),
    "Rejoin": centered("Lua/FileSync/Dark/Large/Refresh@3x.png", 26),
}
menu_strip = Image.new("RGBA", (MENU_SIZE * len(menu_icons), MENU_SIZE))
for index, icon in enumerate(menu_icons.values()):
    menu_strip.alpha_composite(icon, (index * MENU_SIZE, 0))

OUTPUT.write_text(
    "-- Generated by scripts/icons.py from Roblox Studio's icons. Do not edit.\n\n"
    "return {\n"
    "\tClass = {\n"
    f"\t\tSize = {CLASS_SIZE},\n"
    f"\t\tWidth = {CLASS_COLUMNS * CLASS_SIZE},\n"
    f"\t\tHeight = {rows * CLASS_SIZE},\n"
    f"\t\tNames = {{ {names_list(class_names)} }},\n"
    f'\t\tPng = "{encode(class_atlas)}",\n'
    "\t},\n"
    "\tMenu = {\n"
    f"\t\tSize = {MENU_SIZE},\n"
    f"\t\tNames = {{ {names_list(list(menu_icons))} }},\n"
    f'\t\tPng = "{encode(menu_strip)}",\n'
    "\t},\n"
    "}\n",
    newline="\r\n",
)
print(f"{len(class_names)} class icons, {len(menu_icons)} menu icons -> {OUTPUT}")
